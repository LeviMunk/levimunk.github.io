// Build the *same* GitHub Pages trading UI into the authenticated Worker.
// No npm packages, no duplicated source code and no account credentials.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const root = dirname(fileURLToPath(import.meta.url));
const publicDir = resolve(root, "..");
const html = readFileSync(resolve(publicDir, "index.html"), "utf8")
  .replaceAll('href="../"', 'href="https://levimunk.com/"')
  .replace(
    "This public dashboard deliberately does not ask for or store API credentials.",
    "This dashboard is protected by Cloudflare Access and never asks for brokerage credentials."
  );
const app = readFileSync(resolve(publicDir, "app.js"), "utf8");
const css = readFileSync(resolve(publicDir, "styles.css"), "utf8");

writeFileSync(resolve(root, "generated-assets.mjs"),
  "// Generated by build.mjs. Do not edit or commit.\n" +
  "export const assets = " + JSON.stringify({ html, app, css }) + ";\n",
  "utf8");
console.log("Generated authenticated LeviOS Trading UI from GitHub Pages sources.");
