// Bundle the same GitHub Pages trading UI and the pinned, self-hosted
// TradingView Lightweight Charts standalone distribution into the Worker.
// No client-side third-party CDNs and no brokerage credentials in assets.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const root = dirname(fileURLToPath(import.meta.url));
const publicDir = resolve(root, "..");
const repoRoot = resolve(root, "../..");
const chartPath = resolve(repoRoot,
  "node_modules/lightweight-charts/dist/lightweight-charts.standalone.production.js");
if (!existsSync(chartPath)) {
  // Cloudflare currently builds from the repository root using 'node build.mjs'.
  // GitHub Actions also runs that command. Keep the build self-contained when
  // the platform has not installed npm dependencies ahead of time.
  execFileSync("npm", ["install", "--no-audit", "--no-fund",
    "--no-package-lock", "--ignore-scripts", "--omit=dev"], {
    cwd: repoRoot, stdio: "inherit", timeout: 120000
  });
}
if (!existsSync(chartPath)) {
  throw Error("Pinned TradingView Lightweight Charts browser bundle is missing.");
}
const chartLib = readFileSync(chartPath, "utf8");
if (!chartLib.includes("TradingView") && !chartLib.includes("LightweightCharts")) {
  throw Error("Unexpected TradingView bundle content.");
}
const html = readFileSync(resolve(publicDir, "index.html"), "utf8")
  .replaceAll('href="../"', 'href="https://levimunk.com/"')
  // The chart library loads first on the authenticated Worker. GitHub Pages
  // deliberately has no /lightweight-charts.js route; its old SVGs stay usable.
  .replace('<script defer src="./app.js"></script>',
    '<script defer src="./lightweight-charts.js"></script>\n  <script defer src="./app.js"></script>')
  .replace(
    "This public dashboard deliberately does not ask for or store API credentials.",
    "This dashboard is protected by Cloudflare Access and never asks for brokerage credentials."
  );
const app = readFileSync(resolve(publicDir, "app.js"), "utf8");
const strategyEngine = readFileSync(resolve(publicDir, "strategy-engine.js"), "utf8");
const validationEngine = readFileSync(resolve(publicDir, "validation-engine.js"), "utf8");
const coachEngine = readFileSync(resolve(publicDir, "coach-engine.js"), "utf8");
const radarEngine = readFileSync(resolve(publicDir, "radar-engine.js"), "utf8");
const eventsEngine = readFileSync(resolve(publicDir, "events-engine.js"), "utf8");
const earningsEngine = readFileSync(resolve(publicDir, "earnings-engine.js"), "utf8");
const catalystEngine = readFileSync(resolve(publicDir, "catalyst-engine.js"), "utf8");
const journalEngine = readFileSync(resolve(publicDir, "journal-engine.js"), "utf8");
const decisionGuide = readFileSync(resolve(publicDir, "decision-guide.js"), "utf8");
const fundamentalsEngine = readFileSync(resolve(publicDir, "fundamentals-engine.js"), "utf8");
const valuationEngine = readFileSync(resolve(publicDir, "valuation-engine.js"), "utf8");
const css = readFileSync(resolve(publicDir, "styles.css"), "utf8");

writeFileSync(resolve(root, "generated-assets.mjs"),
  "// Generated by build.mjs. Do not edit or commit.\n" +
  "export const assets = " + JSON.stringify({ html, app, css, chartLib, strategyEngine, validationEngine, coachEngine, radarEngine, eventsEngine, earningsEngine, catalystEngine, journalEngine, decisionGuide, fundamentalsEngine, valuationEngine }) + ";\n",
  "utf8");
console.log("Generated authenticated LeviOS with self-hosted TradingView Lightweight Charts.");
